/// The key in a cube record with its population flags.
pub const FLAGS_KEY: &str = "horizon:cubic_flags";
/// The cube's own population ran.
pub const POPULATED: u8 = 1;
/// The record holds terrain and a neighbour's writes only.
pub const PARTIAL: u8 = 2;

/// The cube Ys vanilla's Overworld generator makes (-64..320): Hybrid's band.
pub const VANILLA_CUBES: std::ops::RangeInclusive<i32> = -4..=19;

/// A world's choice of generator: its type and the settings JSON
/// (`cubicgen.json`; empty means the type's defaults).
#[derive(Clone, Debug)]
pub struct CubicGeneration {
    pub kind: CubicKind,
    pub settings_json: String,
}

impl Default for CubicGeneration {
    fn default() -> Self {
        Self {
            kind: CubicKind::Hybrid,
            settings_json: String::new(),
        }
    }
}

impl CubicGeneration {
    /// What a world folder says: its type and `cubicgen.json`
    /// (`cubic_settings::load_world_generation`), Hybrid with the default
    /// settings for a world that says nothing.
    pub fn of_world(dir: &std::path::Path) -> Self {
        match crate::cubic_settings::load_world_generation(dir) {
            Some((kind, settings_json)) => Self {
                kind,
                settings_json,
            },
            None => Self::default(),
        }
    }
}

/// Whether the population of cube `p` runs in a world of `kind`: always in
/// Custom, never in Flat, and in Hybrid when neither `p` nor the cube above
/// it (its region) is in vanilla's range.
pub fn needs_population(kind: CubicKind, p: SectionPos) -> bool {
    match kind {
        CubicKind::Custom => true,
        CubicKind::Flat => false,
        CubicKind::Hybrid => p.y + 1 < *VANILLA_CUBES.start() || p.y > *VANILLA_CUBES.end(),
    }
}

/// Whether cube `y` is generated by vanilla's column generator.
pub fn is_vanilla_cube(kind: CubicKind, y: i32) -> bool {
    kind == CubicKind::Hybrid && VANILLA_CUBES.contains(&y)
}

/// A level's generator and what hangs off it.
pub struct Generation {
    pub kind: CubicKind,
    pub generator: Arc<CustomCubicGenerator>,
    /// The settings in force (default flat settings for Flat).
    pub settings: Option<CustomGeneratorSettings>,
    /// The biome source the generator and the vegetation use (a single biome
    /// where the settings name one).
    pub columns: Arc<dyn BiomeColumns>,
    /// 26.3's climate behind `columns`, when the level has the generator
    /// data: what the far terrain's biome pass is built from.
    pub climate: Option<Arc<ClimateBiomes>>,
    pub vegetation: Option<Arc<Vegetation>>,
    pub seed: i64,
}

impl Generation {
    /// Builds the generator of `choice`. `data` gives the biomes of 26.3's
    /// multi-noise source and its vegetation; without it every column is
    /// plains and nothing grows (tests).
    pub fn new(
        choice: &CubicGeneration,
        seed: i64,
        registry: &'static BlockRegistry,
        data: Option<&Arc<GeneratorData>>,
    ) -> Result<Self, String> {
        let text = if choice.settings_json.trim().is_empty() {
            crate::cubic_settings::default_json(choice.kind)
        } else {
            choice.settings_json.clone()
        };
        if choice.kind == CubicKind::Flat {
            let generator =
                CustomCubicGenerator::flat(&FlatGeneratorSettings::from_json(&text)?, registry)?;
            return Ok(Self {
                kind: choice.kind,
                generator: Arc::new(generator),
                settings: None,
                columns: Arc::new(FixedBiome::new("minecraft:plains")),
                climate: None,
                vegetation: None,
                seed,
            });
        }
        let (settings, warnings) = CustomGeneratorSettings::from_json_with_warnings(&text)?;
        for warning in warnings {
            log::warn!("Horizon: cubicgen.json: {warning}");
        }
        let climate = match data {
            Some(data) => match ClimateBiomes::new(data, seed, settings.biome_scale()) {
                Ok(c) => Some(Arc::new(c)),
                Err(e) => {
                    log::warn!("Horizon: no climate for the cubic biomes ({e}); plains everywhere");
                    None
                }
            },
            None => None,
        };
        let source: Arc<dyn BiomeColumns> = match &climate {
            Some(c) => c.clone(),
            None => Arc::new(FixedBiome::new("minecraft:plains")),
        };
        let generator = CustomCubicGenerator::new(seed, &settings, registry, source.clone())?;
        let columns: Arc<dyn BiomeColumns> = if settings.biome.is_empty() {
            source
        } else {
            Arc::new(FixedBiome::new(&settings.biome))
        };
        let vegetation = match (data, &climate) {
            (Some(data), Some(_)) => Vegetation::new(data, seed).map(Arc::new),
            _ => None,
        };
        Ok(Self {
            kind: choice.kind,
            generator: Arc::new(generator),
            settings: Some(settings),
            columns,
            climate,
            vegetation,
            seed,
        })
    }

    /// The biomes of cube column (`cx`, `cz`) as a section's biome container
    /// (one biome per 4 x 4 column, the same at every height).
    pub fn biome_container(&self, biomes: &Biomes, cx: i32, cz: i32) -> PalettedContainer {
        let mut cells = [0u32; 64];
        for qz in 0..4 {
            for qx in 0..4 {
                let id = self.columns.biome(cx * 4 + qx, cz * 4 + qz);
                let value = u32::from(biomes.id(self.columns.biome_name(id)));
                for qy in 0..4 {
                    cells[((qy << 2 | qz) << 2 | qx) as usize] = value;
                }
            }
        }
        PalettedContainer::from_values(BIOME_STRATEGY, &cells)
    }
}

// --------------------------------------------------------------- flags

/// The population flags of a cube record.
pub fn root_flags(root: &NamedTag) -> u8 {
    match root.tag.get(FLAGS_KEY) {
        Some(Tag::Byte(b)) => *b as u8,
        _ => 0,
    }
}

/// Puts `flags` in a cube record (no key for none).
pub fn set_root_flags(root: &mut NamedTag, flags: u8) {
    if let Tag::Compound(map) = &mut root.tag {
        if flags == 0 {
            map.remove(&FLAGS_KEY.into());
        } else {
            map.insert(FLAGS_KEY.into(), Tag::Byte(flags as i8));
        }
    }
}

// --------------------------------------------------------- the 2x2x2 world

/// The 2 x 2 x 2 cubes from `origin` as the population's world: the blocks
/// of eight cubes, which cubes were written, and the vegetation hook.
pub struct PopRegion {
    origin: SectionPos,
    cubes: [Box<[u32; 4096]>; 8],
    dirty: [bool; 8],
    columns: Arc<dyn BiomeColumns>,
    vegetation: Option<Arc<Vegetation>>,
}

impl PopRegion {
    /// The region from `origin`, cube `d` (`dx | dy << 1 | dz << 2`) from
    /// `cubes[d]`.
    pub fn new(
        origin: SectionPos,
        cubes: &[impl CubeBlocks; 8],
        columns: Arc<dyn BiomeColumns>,
        vegetation: Option<Arc<Vegetation>>,
    ) -> Self {
        let cubes = std::array::from_fn(|d| {
            let mut blocks = Box::new([0u32; 4096]);
            cubes[d].blocks_into(&mut blocks);
            blocks
        });
        Self {
            origin,
            cubes,
            dirty: [false; 8],
            columns,
            vegetation,
        }
    }

    fn locate(&self, p: [i32; 3]) -> Option<(usize, usize)> {
        let o = [self.origin.x, self.origin.y, self.origin.z];
        let mut d = 0;
        let mut i = 0;
        for a in 0..3 {
            let c = (p[a] >> 4) - o[a];
            if !(0..2).contains(&c) {
                return None;
            }
            d |= (c as usize) << a;
        }
        i |= ((p[1] & 15) as usize) << 8 | ((p[2] & 15) as usize) << 4 | (p[0] & 15) as usize;
        Some((d, i))
    }

    /// Which cubes (`dx | dy << 1 | dz << 2`) the population wrote.
    pub fn dirty(&self) -> [bool; 8] {
        self.dirty
    }

    /// Cube `d`'s blocks.
    pub fn blocks(&self, d: usize) -> &[u32; 4096] {
        &self.cubes[d]
    }

    /// The eight cubes' blocks.
    pub fn into_blocks(self) -> [Box<[u32; 4096]>; 8] {
        self.cubes
    }
}

/// What a population region's cube is read from.
pub trait CubeBlocks {
    /// Writes the cube's block states into `out` (index `y << 8 | z << 4 | x`).
    fn blocks_into(&self, out: &mut [u32; 4096]);
}

impl CubeBlocks for Arc<Section> {
    fn blocks_into(&self, out: &mut [u32; 4096]) {
        match self.blocks.uniform() {
            Some(v) => out.fill(v),
            None => self.unpack(out),
        }
    }
}

impl CubeBlocks for Held {
    fn blocks_into(&self, out: &mut [u32; 4096]) {
        match self {
            Held::Section(s) => s.blocks_into(out),
            Held::Blocks(b) => out.copy_from_slice(&b.blocks[..]),
        }
    }
}

/// A cube in flight: a section, or the blocks a population left it with,
/// made into a section (as `Section::from_blocks`, compacted) when first
/// asked for. A cube that population after population changes is not
/// packed and unpacked again for each of them.
#[derive(Clone)]
pub enum Held {
    Section(Arc<Section>),
    Blocks(Arc<HeldBlocks>),
}

pub struct HeldBlocks {
    blocks: Box<[u32; 4096]>,
    biomes: PalettedContainer,
    section: OnceLock<Arc<Section>>,
}

impl Held {
    /// `blocks` with `biomes`, as a population left them.
    pub fn blocks(blocks: Box<[u32; 4096]>, biomes: PalettedContainer) -> Self {
        Held::Blocks(Arc::new(HeldBlocks {
            blocks,
            biomes,
            section: OnceLock::new(),
        }))
    }

    /// The cube as a section.
    pub fn section(&self) -> Arc<Section> {
        match self {
            Held::Section(section) => section.clone(),
            Held::Blocks(b) => b
                .section
                .get_or_init(|| {
                    let mut section = Section {
                        blocks: Section::from_blocks(&b.blocks),
                        biomes: b.biomes.clone(),
                        ..Section::default()
                    };
                    section.compact();
                    Arc::new(section)
                })
                .clone(),
        }
    }

    /// The cube's biomes.
    pub fn biomes(&self) -> PalettedContainer {
        match self {
            Held::Section(section) => section.biomes.clone(),
            Held::Blocks(b) => b.biomes.clone(),
        }
    }
}

impl CubeWorld for PopRegion {
    fn block(&self, p: [i32; 3]) -> u32 {
        self.locate(p).map_or(0, |(d, i)| self.cubes[d][i])
    }
    fn set_block(&mut self, p: [i32; 3], state: u32) {
        if let Some((d, i)) = self.locate(p)
            && self.cubes[d][i] != state
        {
            self.cubes[d][i] = state;
            self.dirty[d] = true;
        }
    }
    fn decorate_surface(&mut self, cube: SectionPos, random: &mut JRandom) {
        if let Some(vegetation) = self.vegetation.clone() {
            let columns = self.columns.clone();
            vegetation.decorate(cube, random, self, &*columns);
        }
    }
}

// ------------------------------------------------------- state in memory

const STRIPES: usize = 1024;
/// Sections of cubes in flight kept at most.
const CACHE_CUBES: usize = 6144;
/// Flags kept at most before the oldest are forgotten (they are in the
/// records).
const FLAG_LIMIT: usize = 1 << 21;

/// What population keeps in memory: flags, in-flight cubes and locks.
pub struct Population {
    stripes: Vec<Mutex<()>>,
    flags: Mutex<HashMap<SectionPos, u8>>,
    cache: Mutex<Cache>,
    pub populations: AtomicU64,
    pub populate_nanos: AtomicU64,
    pub generated: AtomicU64,
    pub generate_nanos: AtomicU64,
}

#[derive(Default)]
struct Cache {
    /// Each cube, and whether it is all its record holds (`plain`).
    map: HashMap<SectionPos, (Held, bool)>,
    order: VecDeque<SectionPos>,
}

impl Default for Population {
    fn default() -> Self {
        Self::new()
    }
}

impl Population {
    pub fn new() -> Self {
        Self {
            stripes: (0..STRIPES).map(|_| Mutex::new(())).collect(),
            flags: Mutex::default(),
            cache: Mutex::default(),
            populations: AtomicU64::new(0),
            populate_nanos: AtomicU64::new(0),
            generated: AtomicU64::new(0),
            generate_nanos: AtomicU64::new(0),
        }
    }

    fn stripe(pos: SectionPos) -> usize {
        let h = (pos.x as u32 as u64).wrapping_mul(0x9E37_79B1_85EB_CA87)
            ^ (pos.y as u32 as u64).wrapping_mul(0xC2B2_AE3D_27D4_EB4F)
            ^ (pos.z as u32 as u64).wrapping_mul(0x1656_67B1_9E37_79F9);
        ((h ^ h >> 29) % STRIPES as u64) as usize
    }

    /// Locks the stripes of the cubes of the region from `origin`, in
    /// ascending stripe order (every population takes them in that order, so
    /// none can wait for another that waits for it).
    pub fn lock_region(&self, origin: SectionPos) -> Vec<std::sync::MutexGuard<'_, ()>> {
        let mut ids: Vec<usize> = (0..8)
            .map(|d| {
                Self::stripe(SectionPos::new(
                    origin.x + (d & 1),
                    origin.y + (d >> 1 & 1),
                    origin.z + (d >> 2 & 1),
                ))
            })
            .collect();
        ids.sort_unstable();
        ids.dedup();
        ids.into_iter()
            .map(|i| self.stripes[i].lock().unwrap_or_else(|e| e.into_inner()))
            .collect()
    }

    /// The flags known for `pos`.
    pub fn flags(&self, pos: SectionPos) -> Option<u8> {
        self.flags.lock().unwrap().get(&pos).copied()
    }

    /// Notes `flags` for `pos` when none are known yet (what a record said).
    pub fn learn_flags(&self, pos: SectionPos, flags: u8) {
        let mut map = self.flags.lock().unwrap();
        if map.len() >= FLAG_LIMIT {
            map.clear();
        }
        map.entry(pos).or_insert(flags);
    }

    /// Sets the flags of `pos` (population ran, record written).
    pub fn set_flags(&self, pos: SectionPos, flags: u8) {
        self.flags.lock().unwrap().insert(pos, flags);
    }

    /// A cube in flight.
    pub fn cached(&self, pos: SectionPos) -> Option<Held> {
        self.cache.lock().unwrap().map.get(&pos).map(|e| e.0.clone())
    }

    /// Whether cube `pos` is in flight with a record that is exactly its
    /// content: written by a population with no entities, and not since.
    pub fn is_plain(&self, pos: SectionPos) -> bool {
        matches!(self.cache.lock().unwrap().map.get(&pos), Some((_, true)))
    }

    /// The section of a plain cube in flight (`is_plain`). Kept as that
    /// section from then on: the blocks a population left are dropped.
    pub fn plain_section(&self, pos: SectionPos) -> Option<Arc<Section>> {
        let held = match self.cache.lock().unwrap().map.get(&pos) {
            Some((held, true)) => held.clone(),
            _ => return None,
        };
        let section = held.section();
        if let Held::Blocks(b) = &held {
            let mut cache = self.cache.lock().unwrap();
            if let Some((entry, true)) = cache.map.get_mut(&pos)
                && matches!(entry, Held::Blocks(now) if Arc::ptr_eq(now, b))
            {
                *entry = Held::Section(section.clone());
            }
        }
        Some(section)
    }

    /// Keeps `held` as cube `pos`'s current content.
    pub fn keep(&self, pos: SectionPos, held: Held) {
        self.keep_as(pos, held, false);
    }

    /// Keeps `held` as cube `pos`'s current content and its whole record
    /// (`is_plain`).
    pub fn keep_plain(&self, pos: SectionPos, held: Held) {
        self.keep_as(pos, held, true);
    }

    fn keep_as(&self, pos: SectionPos, held: Held, plain: bool) {
        let mut cache = self.cache.lock().unwrap();
        if cache.map.insert(pos, (held, plain)).is_none() {
            cache.order.push_back(pos);
        }
        while cache.map.len() > CACHE_CUBES {
            match cache.order.pop_front() {
                Some(old) => {
                    cache.map.remove(&old);
                }
                None => break,
            }
        }
    }

    /// Forgets cube `pos` (its record changed under it).
    pub fn forget(&self, pos: SectionPos) {
        self.cache.lock().unwrap().map.remove(&pos);
    }

    /// Counters: populations run and their mean time, terrain cubes
    /// generated and their mean time (microseconds).
    pub fn stats(&self) -> PopulationStats {
        let load = |a: &AtomicU64| a.load(Ordering::Relaxed);
        let mean = |n: &AtomicU64, t: &AtomicU64| {
            let n = load(n).max(1);
            load(t) as f64 / n as f64 / 1000.0
        };
        PopulationStats {
            populations: load(&self.populations),
            populate_micros: mean(&self.populations, &self.populate_nanos),
            generated: load(&self.generated),
            generate_micros: mean(&self.generated, &self.generate_nanos),
        }
    }
}

/// See [`Population::stats`].
#[derive(Clone, Copy, Debug, Default)]
pub struct PopulationStats {
    pub populations: u64,
    pub populate_micros: f64,
    pub generated: u64,
    pub generate_micros: f64,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hybrid_skips_the_populations_that_touch_vanillas_range() {
        let at = |y| SectionPos::new(0, y, 0);
        for y in -5..=19 {
            assert!(!needs_population(CubicKind::Hybrid, at(y)), "{y}");
        }
        for y in [-6, -100, 20, 300] {
            assert!(needs_population(CubicKind::Hybrid, at(y)), "{y}");
        }
        assert!(needs_population(CubicKind::Custom, at(5)));
        assert!(!needs_population(CubicKind::Flat, at(500)));
    }

    #[test]
    fn flags_round_trip_through_a_record() {
        let mut root = NamedTag {
            name: "".into(),
            tag: Tag::compound([("a", Tag::Int(1))]),
        };
        assert_eq!(root_flags(&root), 0);
        set_root_flags(&mut root, POPULATED | PARTIAL);
        assert_eq!(root_flags(&root), 3);
        set_root_flags(&mut root, 0);
        assert!(root.tag.get(FLAGS_KEY).is_none());
    }

    #[test]
    fn region_locks_are_taken_in_one_order() {
        let pop = Population::new();
        let a = pop.lock_region(SectionPos::new(0, 0, 0));
        drop(a);
        // Two overlapping regions locked one after the other never deadlock.
        let b = pop.lock_region(SectionPos::new(1, 0, 0));
        drop(b);
    }

    #[test]
    fn a_pop_region_reads_and_writes_across_its_cubes() {
        let section = |v: u32| {
            Arc::new(Section {
                blocks: PalettedContainer::new(crate::chunk::block_strategy(), v),
                ..Section::default()
            })
        };
        let sections: [Arc<Section>; 8] = std::array::from_fn(|d| section(d as u32 + 1));
        let mut region = PopRegion::new(
            SectionPos::new(2, -3, 4),
            &sections,
            Arc::new(FixedBiome::new("minecraft:plains")),
            None,
        );
        // Cube (dx, dy, dz) = (1, 0, 1) is index 5.
        assert_eq!(region.block([3 * 16, -3 * 16, 5 * 16]), 6);
        assert_eq!(region.block([2 * 16, -2 * 16 + 5, 4 * 16]), 3);
        assert_eq!(region.block([0, 0, 0]), 0, "outside reads as air");
        region.set_block([3 * 16 + 1, -3 * 16 + 1, 5 * 16 + 1], 99);
        assert!(region.dirty()[5]);
        assert_eq!(region.dirty().iter().filter(|d| **d).count(), 1);
        region.set_block([0, 0, 0], 7);
        assert_eq!(region.dirty().iter().filter(|d| **d).count(), 1);
    }
}
