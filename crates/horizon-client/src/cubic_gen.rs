//! What a cubic level generates its cubes with (docs/cubic-v2-plan.md,
//! "Generation"): the world type, CubicWorldGen's generator for it and the
//! pieces population needs. `cubic.rs` drives them; this file has no I/O.
//!
//! # World types ([`CubicKind`])
//!
//! * **Custom**: every cube from `CustomCubicGenerator`; vanilla's column
//!   generator is never used.
//! * **Hybrid**: vanilla 26.3 between cubes -4..=19, generated once whole and
//!   saved as cubes (v1's behaviour), CubicWorldGen's generator elsewhere.
//!   Cube populations whose 2 x 2 x 2 region touches the vanilla range are
//!   skipped (vanilla decorated that range itself): [`needs_population`].
//! * **Flat**: CubicWorldGen's flat generator, nothing to populate.
//!
//! # Population state
//!
//! A cube's record carries [`FLAGS_KEY`]: bit 0 [`POPULATED`] (the cube's own
//! population ran) and bit 1 [`PARTIAL`] (the record exists only because a
//! neighbour's population wrote into it; the cube's own has not run).
//! [`Population`] holds the in-memory side: the flags known, a cache of the
//! sections of cubes in flight, and the striped locks that serialise
//! populations whose regions overlap.

